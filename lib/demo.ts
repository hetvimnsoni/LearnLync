export function getDemoProfile(keyOrId?: string): DemoProfile {
  if (!keyOrId) return DEMO_PROFILES.elena;
  const direct = DEMO_PROFILES[keyOrId.toLowerCase()];
  if (direct) return direct;
  const byId = Object.values(DEMO_PROFILES).find(
    (p) =>
      p.id === keyOrId ||
      p.email === keyOrId ||
      (p.username && p.username.toLowerCase() === keyOrId.toLowerCase())
  );
  return byId || DEMO_PROFILES.elena;
}
